"""Demo seed data. Fernwood Coffee Roasters is fictional.

Attribute conventions:
- veg/vegan: True/False only where the (fictional) restaurant has verified it;
  None means unknown. Vegetarian follows the Indian convention (no egg).
- allergens: list + "verified" status, or None + "unknown".
- ingredients: "verified" (complete), "partial" (incomplete), or "unknown".
- image: None -> the UI shows a neutral placeholder, never a fake photo.
"""

from decimal import Decimal as D


def item(
    name, price, *, desc, type, temp=None, coffee=None, caffeine=None, strength=None, sweet=None,
    veg=None, vegan=None, ingredients=None, ing_status="unknown", allergens=None, all_status="unknown",
    tags=(), flavors=(), pairs=(), keywords=(), variants=(), variant_required=False, addons=(),
    featured=False, available=True, serves=1, image=None,
):
    return dict(
        name=name, price=D(price), description=desc, item_type=type, temperature=temp, contains_coffee=coffee,
        caffeine_level=caffeine, strength=strength, sweetness=sweet, is_vegetarian=veg, is_vegan=vegan,
        ingredients=list(ingredients) if ingredients is not None else None, ingredients_status=ing_status,
        allergens=list(allergens) if allergens is not None else None, allergens_status=all_status,
        tags=list(tags), flavor_tags=list(flavors), pairs_with=list(pairs), search_keywords=list(keywords),
        variants=[
            dict(name=v[0], price=D(v[1]), is_default=v[2], is_available=v[3] if len(v) > 3 else True) for v in variants
        ],
        variant_required=variant_required, addons=list(addons), is_featured=featured, is_available=available,
        serves=serves, image_url=image,
    )


